// Builds the DCF and LBO Excel workbooks with real formulas (not static
// values), so editing an assumption cell in Excel recalculates the whole
// model. Pure workbook-building logic lives here (testable in Node); the
// browser-only "trigger a download" step (XLSXStyle.writeFile) stays in
// app/page.js.

import XLSXStyle from "xlsx-js-style";

export const CLR = {
  teal: "14B8A6",
  tealSoft: "CFF5EF",
  tealDark: "0B5E54",
  black: "000000",
  white: "FFFFFF",
  rowAlt: "F2F2F5",
  dark: "1A1A2A",
  mid: "60606E",
  subBg: "111113",
  snapshotGray: "E4E4E8",
};

// Number formats shared by both exports.
// USD is displayed in $ thousands (Excel's trailing-comma scaling trick),
// with commas, no decimals, and negatives in parentheses.
const PCT = "0.0%";
const USD = '"$"#,##0,;("$"#,##0,)';
const USD2 = '"$"#,##0.00'; // share price — unscaled, 2 decimals
const NUM0 = "#,##0"; // integer counts (shares outstanding, holding period)
const DF = "0.000"; // discount factor
const MULT = '0.0"x"'; // multiples and credit stats
const MOIC_FMT = '0.00"x"'; // MOIC specifically

function makeSheetHelpers() {
  const ws = {};
  ws["!merges"] = [];
  let maxCol = 0;
  let maxRow = 0;

  const col = (c) => XLSXStyle.utils.encode_col(c);
  const abs = (c, r) => `$${col(c)}$${r + 1}`;
  const rel = (c, r) => `${col(c)}${r + 1}`;

  function setCell(r, c, cell) {
    ws[XLSXStyle.utils.encode_cell({ r, c })] = cell;
    if (c > maxCol) maxCol = c;
    if (r > maxRow) maxRow = r;
  }

  const inputStyle = (numFmt) => ({
    fill: { fgColor: { rgb: CLR.tealSoft } },
    font: { bold: true, sz: 10, color: { rgb: CLR.tealDark } },
    alignment: { horizontal: "right", vertical: "center" },
    ...(numFmt ? { z: numFmt } : {}),
  });
  const labelStyle = (bold) => ({
    font: { bold: !!bold, sz: 10, color: { rgb: CLR.dark } },
    alignment: { horizontal: "left", vertical: "center" },
  });
  const formulaStyle = (bold, numFmt, totalBorder) => ({
    font: { bold: !!bold, sz: 10, color: { rgb: CLR.dark } },
    alignment: { horizontal: "right", vertical: "center" },
    ...(numFmt ? { z: numFmt } : {}),
    ...(totalBorder ? { border: { top: { style: "thin", color: { rgb: "10A696" } } } } : {}),
  });
  const headerStyle = () => ({
    font: { bold: true, sz: 10, color: { rgb: CLR.black } },
    fill: { fgColor: { rgb: CLR.teal } },
    alignment: { horizontal: "right", vertical: "center" },
  });

  const setInput = (r, c, value, numFmt) => setCell(r, c, { v: value, t: "n", s: inputStyle(numFmt) });
  const setLabel = (r, c, text, bold) => setCell(r, c, { v: text, t: "s", s: labelStyle(bold) });
  const setFormula = (r, c, formula, numFmt, bold, totalBorder) =>
    setCell(r, c, { f: formula, t: "n", s: formulaStyle(bold, numFmt, totalBorder) });
  const setHeader = (r, c, text) => setCell(r, c, { v: text, t: "s", s: headerStyle() });
  const setErrorCell = (r, c, text) =>
    setCell(r, c, { v: text, t: "s", s: { font: { sz: 10, color: { rgb: "B00020" } }, alignment: { horizontal: "right", vertical: "center" } } });
  const setPlainNum = (r, c, value, numFmt) =>
    setCell(r, c, { v: value, t: "n", z: numFmt, s: { font: { sz: 10, color: { rgb: CLR.dark } }, alignment: { horizontal: "right", vertical: "center" } } });
  // Same as setPlainNum, but with a light gray fill — marks a cell as a
  // computed value from an iterative solver rather than a live formula
  // (used by the cap table export, where the round math and exit waterfall
  // are genuinely circular and can't be expressed as portable formulas).
  const setSnapshotNum = (r, c, value, numFmt, bold) =>
    setCell(r, c, { v: value, t: "n", z: numFmt, s: { fill: { fgColor: { rgb: CLR.snapshotGray } }, font: { bold: !!bold, sz: 10, color: { rgb: CLR.dark } }, alignment: { horizontal: "right", vertical: "center" } } });

  function finalize() {
    ws["!ref"] = XLSXStyle.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: maxRow, c: maxCol } });
    const widths = [30];
    for (let c = 1; c <= maxCol; c++) widths.push(14);
    ws["!cols"] = widths.map((w) => ({ wch: w }));
    return ws;
  }

  return { ws, col, abs, rel, setCell, setInput, setLabel, setFormula, setHeader, setErrorCell, setPlainNum, setSnapshotNum, finalize };
}

function titleBlock(h, title) {
  const { setCell, ws } = h;
  let R = 0;
  for (let c = 0; c <= 5; c++) {
    setCell(R, c, {
      v: c === 0 ? title : "",
      t: "s",
      s: { fill: { fgColor: { rgb: CLR.teal } }, font: { bold: true, sz: 16, color: { rgb: CLR.black } }, alignment: { horizontal: "left", vertical: "center" } },
    });
  }
  ws["!merges"].push({ s: { r: R, c: 0 }, e: { r: R, c: 5 } });
  R++;
  const dateStr = new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
  for (let c = 0; c <= 5; c++) {
    setCell(R, c, {
      v: c === 0 ? `Generated by FinModel AI  ·  ${dateStr}  ·  teal cells are AI-sourced inputs, everything else is a live formula` : "",
      t: "s",
      s: { fill: { fgColor: { rgb: CLR.subBg } }, font: { italic: true, sz: 9, color: { rgb: CLR.mid } }, alignment: { horizontal: "left", vertical: "center" } },
    });
  }
  ws["!merges"].push({ s: { r: R, c: 0 }, e: { r: R, c: 5 } });
  R += 2;
  return R;
}

// Builds the DCF workbook. Returns { wb, refs } — refs exposes every row's
// 0-indexed row number (and the Year1-5 = columns 1-5 convention for
// projection rows) so tests can read specific cells without re-deriving the
// sheet layout.
export function buildDCFWorkbook(assumptions, sensitivity) {
  const a = assumptions;
  const h = makeSheetHelpers();
  const { ws, abs, rel, setInput, setLabel, setFormula } = h;

  let R = titleBlock(h, `DCF Model — ${a.companyName}`);

  // ── Assumptions block ──
  setLabel(R, 0, "Assumptions", true); R++;
  const rowBaseRevenue = R; setLabel(R, 0, "Base revenue ($)"); setInput(R, 1, a.baseRevenue, USD); R++;
  const rowEbitdaMargin = R; setLabel(R, 0, "EBITDA margin"); setInput(R, 1, a.ebitdaMargin, PCT); R++;
  const rowTax = R; setLabel(R, 0, "Tax rate"); setInput(R, 1, a.taxRate, PCT); R++;
  const rowDA = R; setLabel(R, 0, "D&A (% of revenue)"); setInput(R, 1, a.daPct, PCT); R++;
  const rowCapex = R; setLabel(R, 0, "CapEx (% of revenue)"); setInput(R, 1, a.capexPct, PCT); R++;
  const rowNWC = R; setLabel(R, 0, "Change in NWC (% of revenue)"); setInput(R, 1, a.nwcPct, PCT); R++;
  const rowWacc = R; setLabel(R, 0, "WACC"); setInput(R, 1, a.wacc, PCT); R++;
  const rowTermGrowth = R; setLabel(R, 0, "Terminal growth rate"); setInput(R, 1, a.terminalGrowth, PCT); R++;
  const rowNetDebt = R; setLabel(R, 0, "Net debt ($)"); setInput(R, 1, a.netDebt, USD); R++;
  const rowShares = R; setLabel(R, 0, "Shares outstanding"); setInput(R, 1, a.sharesOutstanding, NUM0); R++;
  R++;

  // ── Projection table (Year 1 - Year 5, all 5 years) ──
  const rowYearHeader = R++;
  const rowGrowth = R++;
  const rowRevenue = R++;
  const rowEbitda = R++;
  const rowDAline = R++;
  const rowEbit = R++;
  const rowTaxes = R++;
  const rowNopat = R++;
  const rowCapexLine = R++;
  const rowNwcLine = R++;
  const rowUfcf = R++;
  const rowDF = R++;
  const rowPV = R++;
  R++;

  for (let yc = 1; yc <= 5; yc++) h.setHeader(rowYearHeader, yc, `Year ${yc}`);

  setLabel(rowGrowth, 0, "Revenue growth");
  for (let yc = 1; yc <= 5; yc++) setInput(rowGrowth, yc, a.revenueGrowth[yc - 1], PCT);

  setLabel(rowRevenue, 0, "Revenue", true);
  for (let yc = 1; yc <= 5; yc++) {
    const f = yc === 1 ? `${abs(1, rowBaseRevenue)}*(1+${rel(yc, rowGrowth)})` : `${rel(yc - 1, rowRevenue)}*(1+${rel(yc, rowGrowth)})`;
    setFormula(rowRevenue, yc, f, USD, true);
  }

  setLabel(rowEbitda, 0, "EBITDA", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rowEbitda, yc, `${rel(yc, rowRevenue)}*${abs(1, rowEbitdaMargin)}`, USD, true);

  setLabel(rowDAline, 0, "D&A");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowDAline, yc, `${rel(yc, rowRevenue)}*${abs(1, rowDA)}`, USD);

  setLabel(rowEbit, 0, "EBIT");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowEbit, yc, `${rel(yc, rowEbitda)}-${rel(yc, rowDAline)}`, USD);

  setLabel(rowTaxes, 0, "Taxes");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowTaxes, yc, `MAX(${rel(yc, rowEbit)},0)*${abs(1, rowTax)}`, USD);

  setLabel(rowNopat, 0, "NOPAT");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowNopat, yc, `${rel(yc, rowEbit)}-${rel(yc, rowTaxes)}`, USD);

  setLabel(rowCapexLine, 0, "CapEx");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowCapexLine, yc, `${rel(yc, rowRevenue)}*${abs(1, rowCapex)}`, USD);

  setLabel(rowNwcLine, 0, "Change in NWC");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowNwcLine, yc, `${rel(yc, rowRevenue)}*${abs(1, rowNWC)}`, USD);

  setLabel(rowUfcf, 0, "Unlevered free cash flow", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rowUfcf, yc, `${rel(yc, rowNopat)}+${rel(yc, rowDAline)}-${rel(yc, rowCapexLine)}-${rel(yc, rowNwcLine)}`, USD, true, true);

  setLabel(rowDF, 0, "Discount factor");
  for (let yc = 1; yc <= 5; yc++) setFormula(rowDF, yc, `1/(1+${abs(1, rowWacc)})^${yc}`, DF);

  setLabel(rowPV, 0, "Present value of FCF", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rowPV, yc, `${rel(yc, rowUfcf)}*${rel(yc, rowDF)}`, USD, true);

  // ── Valuation — terminal value uses year 5's UFCF; EV sums all 5 PVs + PV of TV ──
  const rowSumPV = R; setLabel(R, 0, "Sum of PV (Years 1–5)"); setFormula(R, 1, `SUM(${rel(1, rowPV)}:${rel(5, rowPV)})`, USD); R++;
  const rowTV = R; setLabel(R, 0, "Terminal value"); setFormula(R, 1, `${rel(5, rowUfcf)}*(1+${abs(1, rowTermGrowth)})/(${abs(1, rowWacc)}-${abs(1, rowTermGrowth)})`, USD); R++;
  const rowPVTV = R; setLabel(R, 0, "PV of terminal value"); setFormula(R, 1, `${rel(1, rowTV)}*${rel(5, rowDF)}`, USD); R++;
  const rowEV = R; setLabel(R, 0, "Enterprise value", true); setFormula(R, 1, `${rel(1, rowSumPV)}+${rel(1, rowPVTV)}`, USD, true, true); R++;
  const rowLessDebt = R; setLabel(R, 0, "Less: net debt"); setFormula(R, 1, `-${abs(1, rowNetDebt)}`, USD); R++;
  const rowEQ = R; setLabel(R, 0, "Equity value", true); setFormula(R, 1, `${rel(1, rowEV)}+${rel(1, rowLessDebt)}`, USD, true, true); R++;
  const rowSharesRef = R; setLabel(R, 0, "Shares outstanding"); setFormula(R, 1, `${abs(1, rowShares)}`, NUM0); R++;
  const rowSharePrice = R; setLabel(R, 0, "Implied share price", true); setFormula(R, 1, `${rel(1, rowEQ)}/${rel(1, rowSharesRef)}`, USD2, true, true); R++;
  R++;

  // ── Sensitivity (computed snapshot — a native 2-variable data table isn't portable via this writer) ──
  setLabel(R, 0, "Sensitivity — implied share price (snapshot)", true); R++;
  setLabel(R, 0, "WACC ↓ / Terminal growth →");
  for (let gi = 0; gi < sensitivity.growthSteps.length; gi++) {
    const addr = XLSXStyle.utils.encode_cell({ r: R, c: gi + 1 });
    ws[addr] = { v: sensitivity.growthSteps[gi], t: "n", z: PCT, s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, fill: { fgColor: { rgb: CLR.teal } }, alignment: { horizontal: "right", vertical: "center" } } };
  }
  R++;
  sensitivity.grid.forEach((row, wi) => {
    setLabel(R, 0, `${(sensitivity.waccSteps[wi] * 100).toFixed(1)}%`, true);
    row.forEach((cell, gi) => {
      if (cell.error) h.setErrorCell(R, gi + 1, "n/a");
      else h.setPlainNum(R, gi + 1, cell.price, USD2);
    });
    R++;
  });
  R++;

  setLabel(R, 0, "Assumptions were generated by AI and should be verified; every calculation above is a live Excel formula.");
  R++;

  const ws_ = h.finalize();
  const wb = XLSXStyle.utils.book_new();
  XLSXStyle.utils.book_append_sheet(wb, ws_, "DCF Model");

  return {
    wb,
    refs: {
      rows: {
        baseRevenue: rowBaseRevenue, ebitdaMargin: rowEbitdaMargin, taxRate: rowTax, da: rowDA,
        capex: rowCapex, nwc: rowNWC, wacc: rowWacc, terminalGrowth: rowTermGrowth, netDebt: rowNetDebt, shares: rowShares,
        growth: rowGrowth, revenue: rowRevenue, ebitda: rowEbitda, daLine: rowDAline, ebit: rowEbit,
        taxes: rowTaxes, nopat: rowNopat, capexLine: rowCapexLine, nwcLine: rowNwcLine, ufcf: rowUfcf,
        discountFactor: rowDF, pv: rowPV,
        sumPV: rowSumPV, terminalValue: rowTV, pvTerminalValue: rowPVTV, enterpriseValue: rowEV,
        lessDebt: rowLessDebt, equityValue: rowEQ, sharesRef: rowSharesRef, impliedSharePrice: rowSharePrice,
      },
    },
  };
}

// Builds the LBO workbook. Returns { wb, refs } — refs exposes every row's
// 0-indexed row number so tests can read specific cells directly. The
// sponsor cash flow row spans Entry + Year 1-5 (6 cells, columns 1-6) and
// IRR references that full range.
export function buildLBOWorkbook(assumptions, sensitivity) {
  const a = assumptions;
  const h = makeSheetHelpers();
  const { abs, rel, setInput, setLabel, setFormula } = h;

  let R = titleBlock(h, `LBO Model — ${a.companyName}`);

  // ── Assumptions block ──
  setLabel(R, 0, "Assumptions", true); R++;
  const rEntryRevenue = R; setLabel(R, 0, "Entry revenue ($)"); setInput(R, 1, a.entryRevenue, USD); R++;
  const rEbitdaMargin = R; setLabel(R, 0, "EBITDA margin"); setInput(R, 1, a.ebitdaMargin, PCT); R++;
  const rDA = R; setLabel(R, 0, "D&A (% of revenue)"); setInput(R, 1, a.daPct, PCT); R++;
  const rCapex = R; setLabel(R, 0, "CapEx (% of revenue)"); setInput(R, 1, a.capexPct, PCT); R++;
  const rNWC = R; setLabel(R, 0, "Change in NWC (% of revenue)"); setInput(R, 1, a.nwcPct, PCT); R++;
  const rTax = R; setLabel(R, 0, "Tax rate"); setInput(R, 1, a.taxRate, PCT); R++;
  const rEntryMultiple = R; setLabel(R, 0, "Entry EV / EBITDA"); setInput(R, 1, a.entryMultiple, MULT); R++;
  const rExitMultiple = R; setLabel(R, 0, "Exit EV / EBITDA"); setInput(R, 1, a.exitMultiple, MULT); R++;
  const rHoldingPeriod = R; setLabel(R, 0, "Holding period (years)"); setInput(R, 1, a.holdingPeriod, NUM0); R++;
  const rFeePct = R; setLabel(R, 0, "Transaction fees (% of EV)"); setInput(R, 1, a.feePct, PCT); R++;
  const rMinCash = R; setLabel(R, 0, "Minimum cash balance ($)"); setInput(R, 1, a.minCash, USD); R++;
  const rSeniorMultiple = R; setLabel(R, 0, "Senior debt (x EBITDA)"); setInput(R, 1, a.seniorDebt.multiple, MULT); R++;
  const rSeniorRate = R; setLabel(R, 0, "Senior debt interest rate"); setInput(R, 1, a.seniorDebt.rate, PCT); R++;
  const rSeniorAmortPct = R; setLabel(R, 0, "Senior mandatory amort (% of orig.)"); setInput(R, 1, a.seniorDebt.amortPct, PCT); R++;
  const rSubMultiple = R; setLabel(R, 0, "Sub debt (x EBITDA)"); setInput(R, 1, a.subDebt.multiple, MULT); R++;
  const rSubRate = R; setLabel(R, 0, "Sub debt interest rate"); setInput(R, 1, a.subDebt.rate, PCT); R++;
  const rSweepPct = R; setLabel(R, 0, "Cash sweep (% of excess FCF)"); setInput(R, 1, a.sweepPct, PCT); R++;
  R++;

  // ── Sources & uses ──
  setLabel(R, 0, "Sources & uses", true); R++;
  const rEntryEbitda = R; setLabel(R, 0, "Entry EBITDA"); setFormula(R, 1, `${abs(1, rEntryRevenue)}*${abs(1, rEbitdaMargin)}`, USD); R++;
  const rEntryEV = R; setLabel(R, 0, "Entry enterprise value", true); setFormula(R, 1, `${abs(1, rEntryEbitda)}*${abs(1, rEntryMultiple)}`, USD, true); R++;
  const rFees = R; setLabel(R, 0, "Transaction fees"); setFormula(R, 1, `${abs(1, rEntryEV)}*${abs(1, rFeePct)}`, USD); R++;
  const rUses = R; setLabel(R, 0, "Total uses", true); setFormula(R, 1, `${abs(1, rEntryEV)}+${abs(1, rFees)}+${abs(1, rMinCash)}`, USD, true, true); R++;
  const rSeniorOrig = R; setLabel(R, 0, "Senior debt (at close)"); setFormula(R, 1, `${abs(1, rEntryEbitda)}*${abs(1, rSeniorMultiple)}`, USD); R++;
  const rSubOrig = R; setLabel(R, 0, "Sub debt (at close)"); setFormula(R, 1, `${abs(1, rEntryEbitda)}*${abs(1, rSubMultiple)}`, USD); R++;
  const rSponsorEquity = R; setLabel(R, 0, "Sponsor equity (plug)", true); setFormula(R, 1, `${abs(1, rUses)}-${abs(1, rSeniorOrig)}-${abs(1, rSubOrig)}`, USD, true, true); R++;
  R++;

  // ── Projection + debt schedule (Year 1 - Year 5, all 5 years) ──
  // Row numbers are allocated up front (two-pass) so the beginning-balance
  // rows can reference the ending-balance rows below them in the sheet.
  const rYearHeader = R++;
  const rGrowth = R++;
  const rRevenue = R++;
  const rEbitda = R++;
  const rDAline = R++;
  const rEbit = R++;
  const rSeniorBegin = R++;
  const rSubBegin = R++;
  const rInterest = R++;
  const rPretax = R++;
  const rTaxes = R++;
  const rNetIncome = R++;
  const rCapexLine = R++;
  const rNwcLine = R++;
  const rFcf = R++;
  const rMandAmort = R++;
  const rRemAfterMand = R++;
  const rSweep = R++;
  const rSeniorEnd = R++;
  const rSubEnd = R++;
  const rCash = R++;
  const rTotalDebt = R++;
  const rNetDebt = R++;
  const rDebtToEbitda = R++;
  const rIntCoverage = R++;
  R++;

  for (let yc = 1; yc <= 5; yc++) h.setHeader(rYearHeader, yc, `Year ${yc}`);

  setLabel(rGrowth, 0, "Revenue growth");
  for (let yc = 1; yc <= 5; yc++) setInput(rGrowth, yc, a.revenueGrowth[yc - 1], PCT);

  setLabel(rRevenue, 0, "Revenue", true);
  for (let yc = 1; yc <= 5; yc++) {
    const f = yc === 1 ? `${abs(1, rEntryRevenue)}*(1+${rel(yc, rGrowth)})` : `${rel(yc - 1, rRevenue)}*(1+${rel(yc, rGrowth)})`;
    setFormula(rRevenue, yc, f, USD, true);
  }

  setLabel(rEbitda, 0, "EBITDA", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rEbitda, yc, `${rel(yc, rRevenue)}*${abs(1, rEbitdaMargin)}`, USD, true);

  setLabel(rDAline, 0, "D&A");
  for (let yc = 1; yc <= 5; yc++) setFormula(rDAline, yc, `${rel(yc, rRevenue)}*${abs(1, rDA)}`, USD);

  setLabel(rEbit, 0, "EBIT");
  for (let yc = 1; yc <= 5; yc++) setFormula(rEbit, yc, `${rel(yc, rEbitda)}-${rel(yc, rDAline)}`, USD);

  setLabel(rSeniorBegin, 0, "Senior debt, beginning balance");
  for (let yc = 1; yc <= 5; yc++) setFormula(rSeniorBegin, yc, yc === 1 ? `${abs(1, rSeniorOrig)}` : `${rel(yc - 1, rSeniorEnd)}`, USD);

  setLabel(rSubBegin, 0, "Sub debt, beginning balance");
  for (let yc = 1; yc <= 5; yc++) setFormula(rSubBegin, yc, yc === 1 ? `${abs(1, rSubOrig)}` : `${rel(yc - 1, rSubEnd)}`, USD);

  setLabel(rInterest, 0, "Interest expense");
  for (let yc = 1; yc <= 5; yc++) setFormula(rInterest, yc, `${rel(yc, rSeniorBegin)}*${abs(1, rSeniorRate)}+${rel(yc, rSubBegin)}*${abs(1, rSubRate)}`, USD);

  setLabel(rPretax, 0, "Pretax income");
  for (let yc = 1; yc <= 5; yc++) setFormula(rPretax, yc, `${rel(yc, rEbit)}-${rel(yc, rInterest)}`, USD);

  setLabel(rTaxes, 0, "Taxes");
  for (let yc = 1; yc <= 5; yc++) setFormula(rTaxes, yc, `MAX(${rel(yc, rPretax)},0)*${abs(1, rTax)}`, USD);

  setLabel(rNetIncome, 0, "Net income");
  for (let yc = 1; yc <= 5; yc++) setFormula(rNetIncome, yc, `${rel(yc, rPretax)}-${rel(yc, rTaxes)}`, USD);

  setLabel(rCapexLine, 0, "CapEx");
  for (let yc = 1; yc <= 5; yc++) setFormula(rCapexLine, yc, `${rel(yc, rRevenue)}*${abs(1, rCapex)}`, USD);

  setLabel(rNwcLine, 0, "Change in NWC");
  for (let yc = 1; yc <= 5; yc++) setFormula(rNwcLine, yc, `${rel(yc, rRevenue)}*${abs(1, rNWC)}`, USD);

  setLabel(rFcf, 0, "FCF available for debt paydown", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rFcf, yc, `${rel(yc, rNetIncome)}+${rel(yc, rDAline)}-${rel(yc, rCapexLine)}-${rel(yc, rNwcLine)}`, USD, true);

  setLabel(rMandAmort, 0, "Mandatory amortization");
  for (let yc = 1; yc <= 5; yc++) setFormula(rMandAmort, yc, `MIN(${abs(1, rSeniorAmortPct)}*${abs(1, rSeniorOrig)},${rel(yc, rSeniorBegin)})`, USD);

  setLabel(rRemAfterMand, 0, "FCF after mandatory amort");
  for (let yc = 1; yc <= 5; yc++) setFormula(rRemAfterMand, yc, `${rel(yc, rFcf)}-${rel(yc, rMandAmort)}`, USD);

  setLabel(rSweep, 0, "Cash sweep");
  for (let yc = 1; yc <= 5; yc++) setFormula(rSweep, yc, `MIN(${abs(1, rSweepPct)}*MAX(${rel(yc, rRemAfterMand)},0),${rel(yc, rSeniorBegin)}-${rel(yc, rMandAmort)})`, USD);

  setLabel(rSeniorEnd, 0, "Senior debt, ending balance", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rSeniorEnd, yc, `${rel(yc, rSeniorBegin)}-${rel(yc, rMandAmort)}-${rel(yc, rSweep)}`, USD, true);

  setLabel(rSubEnd, 0, "Sub debt, ending balance");
  for (let yc = 1; yc <= 5; yc++) setFormula(rSubEnd, yc, `${rel(yc, rSubBegin)}`, USD);

  setLabel(rCash, 0, "Cash balance", true);
  for (let yc = 1; yc <= 5; yc++) {
    const f = yc === 1
      ? `${abs(1, rMinCash)}+(${rel(yc, rRemAfterMand)}-${rel(yc, rSweep)})`
      : `${rel(yc - 1, rCash)}+(${rel(yc, rRemAfterMand)}-${rel(yc, rSweep)})`;
    setFormula(rCash, yc, f, USD, true);
  }

  setLabel(rTotalDebt, 0, "Total debt");
  for (let yc = 1; yc <= 5; yc++) setFormula(rTotalDebt, yc, `${rel(yc, rSeniorEnd)}+${rel(yc, rSubEnd)}`, USD);

  setLabel(rNetDebt, 0, "Net debt", true);
  for (let yc = 1; yc <= 5; yc++) setFormula(rNetDebt, yc, `${rel(yc, rTotalDebt)}-${rel(yc, rCash)}`, USD, true);

  setLabel(rDebtToEbitda, 0, "Total debt / EBITDA");
  for (let yc = 1; yc <= 5; yc++) setFormula(rDebtToEbitda, yc, `${rel(yc, rTotalDebt)}/${rel(yc, rEbitda)}`, MULT);

  setLabel(rIntCoverage, 0, "EBITDA / interest");
  for (let yc = 1; yc <= 5; yc++) setFormula(rIntCoverage, yc, `${rel(yc, rEbitda)}/${rel(yc, rInterest)}`, MULT);

  // ── Exit & returns ──
  setLabel(R, 0, "Exit & returns", true); R++;
  const rExitEbitda = R; setLabel(R, 0, "Exit EBITDA (at holding period)"); setFormula(R, 1, `INDEX(${rel(1, rEbitda)}:${rel(5, rEbitda)},1,${abs(1, rHoldingPeriod)})`, USD); R++;
  const rExitEV = R; setLabel(R, 0, "Exit enterprise value", true); setFormula(R, 1, `${abs(1, rExitEbitda)}*${abs(1, rExitMultiple)}`, USD, true); R++;
  const rExitNetDebt = R; setLabel(R, 0, "Exit net debt"); setFormula(R, 1, `INDEX(${rel(1, rNetDebt)}:${rel(5, rNetDebt)},1,${abs(1, rHoldingPeriod)})`, USD); R++;
  const rExitEquity = R; setLabel(R, 0, "Exit equity value", true); setFormula(R, 1, `${abs(1, rExitEV)}-${abs(1, rExitNetDebt)}`, USD, true, true); R++;
  const rSponsorProceeds = R; setLabel(R, 0, "Sponsor proceeds"); setFormula(R, 1, `MAX(${abs(1, rExitEquity)},0)`, USD); R++;
  const rMoic = R; setLabel(R, 0, "MOIC", true); setFormula(R, 1, `${abs(1, rSponsorProceeds)}/${abs(1, rSponsorEquity)}`, MOIC_FMT, true, true); R++;
  R++;

  // Sponsor cash flow — Entry (col 1) plus one column for every projection
  // year, Year 1 - Year 5 (cols 2-6). Exit proceeds land in the column
  // matching the holding period; every other year is 0. IRR's range must
  // span all 6 cells (Entry through Year 5) or it silently drops Year 5
  // and can return #NUM! if the holding period lands outside the range.
  setLabel(R, 0, "Sponsor cash flow (Entry → Year 5)");
  const cfLabels = ["Entry", "Year 1", "Year 2", "Year 3", "Year 4", "Year 5"];
  cfLabels.forEach((lbl, i) => h.setHeader(R, i + 1, lbl));
  R++;
  const rCashFlow = R; setLabel(R, 0, "Cash flow");
  setFormula(R, 1, `-${abs(1, rSponsorEquity)}`, USD);
  for (let yc = 1; yc <= 5; yc++) {
    setFormula(R, yc + 1, `IF(${yc}=${abs(1, rHoldingPeriod)},${abs(1, rSponsorProceeds)},0)`, USD);
  }
  R++;
  const rIRR = R; setLabel(R, 0, "IRR", true); setFormula(R, 1, `IRR(${rel(1, rCashFlow)}:${rel(6, rCashFlow)})`, PCT, true, true); R++;
  R++;

  // ── Sensitivity (computed snapshot — a native 2-variable data table isn't portable via this writer) ──
  setLabel(R, 0, "Sensitivity — sponsor IRR (snapshot)", true); R++;
  setLabel(R, 0, "Entry multiple ↓ / Exit multiple →");
  for (let xi = 0; xi < sensitivity.exitSteps.length; xi++) {
    const addr = XLSXStyle.utils.encode_cell({ r: R, c: xi + 1 });
    h.ws[addr] = { v: sensitivity.exitSteps[xi], t: "n", z: MULT, s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, fill: { fgColor: { rgb: CLR.teal } }, alignment: { horizontal: "right", vertical: "center" } } };
  }
  R++;
  sensitivity.grid.forEach((row, ei) => {
    setLabel(R, 0, `${sensitivity.entrySteps[ei].toFixed(1)}x`, true);
    row.forEach((cell, xi) => {
      if (cell.error) h.setErrorCell(R, xi + 1, "n/a");
      else h.setPlainNum(R, xi + 1, cell.irr, PCT);
    });
    R++;
  });
  R++;

  setLabel(R, 0, "Assumptions were generated by AI and should be verified; every calculation above is a live Excel formula.");
  R++;

  const ws_ = h.finalize();
  const wb = XLSXStyle.utils.book_new();
  XLSXStyle.utils.book_append_sheet(wb, ws_, "LBO Model");

  return {
    wb,
    refs: {
      rows: {
        entryRevenue: rEntryRevenue, ebitdaMargin: rEbitdaMargin, da: rDA, capex: rCapex, nwc: rNWC, tax: rTax,
        entryMultiple: rEntryMultiple, exitMultiple: rExitMultiple, holdingPeriod: rHoldingPeriod, feePct: rFeePct, minCash: rMinCash,
        seniorMultiple: rSeniorMultiple, seniorRate: rSeniorRate, seniorAmortPct: rSeniorAmortPct,
        subMultiple: rSubMultiple, subRate: rSubRate, sweepPct: rSweepPct,
        entryEbitda: rEntryEbitda, entryEV: rEntryEV, fees: rFees, uses: rUses,
        seniorOrig: rSeniorOrig, subOrig: rSubOrig, sponsorEquity: rSponsorEquity,
        growth: rGrowth, revenue: rRevenue, ebitda: rEbitda, daLine: rDAline, ebit: rEbit,
        seniorBegin: rSeniorBegin, subBegin: rSubBegin, interest: rInterest, pretax: rPretax,
        taxes: rTaxes, netIncome: rNetIncome, capexLine: rCapexLine, nwcLine: rNwcLine, fcf: rFcf,
        mandAmort: rMandAmort, remAfterMand: rRemAfterMand, sweep: rSweep,
        seniorEnd: rSeniorEnd, subEnd: rSubEnd, cash: rCash, totalDebt: rTotalDebt, netDebt: rNetDebt,
        debtToEbitda: rDebtToEbitda, intCoverage: rIntCoverage,
        exitEbitda: rExitEbitda, exitEV: rExitEV, exitNetDebt: rExitNetDebt, exitEquity: rExitEquity,
        sponsorProceeds: rSponsorProceeds, moic: rMoic,
        cashFlow: rCashFlow, irr: rIRR,
      },
    },
  };
}

// Builds the unit economics workbook. Returns { wb, refs }. The full
// month-by-month cohort table (survival, expected gross profit, cumulative
// gross profit, discounted gross profit) is entirely live formulas, as is
// the CAC payback month (via COUNTIF + INDEX to find and interpolate the
// crossing month) and the churn x CAC sensitivity grid.
export function buildUnitEconomicsWorkbook(assumptions, sensitivity) {
  const a = assumptions;
  const h = makeSheetHelpers();
  const { abs, rel, setInput, setLabel, setFormula } = h;
  const months = a.projectionMonths;

  let R = titleBlock(h, `Unit Economics — ${a.companyName}`);

  // ── Assumptions block ──
  setLabel(R, 0, "Assumptions", true); R++;
  const rArpu = R; setLabel(R, 0, "ARPU, monthly ($)"); setInput(R, 1, a.arpu, USD2); R++;
  const rMargin = R; setLabel(R, 0, "Gross margin"); setInput(R, 1, a.grossMargin, PCT); R++;
  const rChurn = R; setLabel(R, 0, "Monthly churn"); setInput(R, 1, a.monthlyChurn, PCT); R++;
  const rCac = R; setLabel(R, 0, "CAC ($)"); setInput(R, 1, a.cac, USD2); R++;
  const rDiscount = R; setLabel(R, 0, "Monthly discount rate"); setInput(R, 1, a.monthlyDiscountRate, PCT); R++;
  const rMonths = R; setLabel(R, 0, "Projection months"); setInput(R, 1, months, NUM0); R++;
  R++;

  // ── Derived single-value metrics ──
  const rGrossProfit = R; setLabel(R, 0, "Gross profit per customer / month", true); setFormula(R, 1, `${abs(1, rArpu)}*${abs(1, rMargin)}`, USD2, true); R++;
  R++;

  // ── Monthly cohort table (1 column per projection month) ──
  const rMonthHeader = R++;
  const rSurvival = R++;
  const rExpectedGP = R++;
  const rCumulativeGP = R++;
  const rDiscountedGP = R++;
  const rPaybackFlag = R++;
  R++;

  for (let m = 1; m <= months; m++) h.setHeader(rMonthHeader, m, `Month ${m}`);

  setLabel(rSurvival, 0, "Survival probability");
  for (let m = 1; m <= months; m++) {
    const f = m === 1 ? "1" : `${rel(m - 1, rSurvival)}*(1-${abs(1, rChurn)})`;
    setFormula(rSurvival, m, f, "0.000");
  }

  setLabel(rExpectedGP, 0, "Expected gross profit", true);
  for (let m = 1; m <= months; m++) setFormula(rExpectedGP, m, `${rel(m, rSurvival)}*${abs(1, rGrossProfit)}`, USD2, true);

  setLabel(rCumulativeGP, 0, "Cumulative gross profit", true);
  for (let m = 1; m <= months; m++) {
    const f = m === 1 ? `${rel(1, rExpectedGP)}` : `${rel(m - 1, rCumulativeGP)}+${rel(m, rExpectedGP)}`;
    setFormula(rCumulativeGP, m, f, USD2, true);
  }

  setLabel(rDiscountedGP, 0, "Discounted expected gross profit");
  for (let m = 1; m <= months; m++) setFormula(rDiscountedGP, m, `${rel(m, rExpectedGP)}/(1+${abs(1, rDiscount)})^${m}`, USD2);

  setLabel(rPaybackFlag, 0, "Payback reached?");
  for (let m = 1; m <= months; m++) setFormula(rPaybackFlag, m, `IF(${rel(m, rCumulativeGP)}>=${abs(1, rCac)},"Yes","")`, "@");

  // ── Summary metrics derived from the cohort table ──
  const rAvgLifetime = R; setLabel(R, 0, "Average customer lifetime (months)"); setFormula(R, 1, `IF(${abs(1, rChurn)}>0,1/${abs(1, rChurn)},"n/a")`, "0.0"); R++;
  const rSimpleLTV = R; setLabel(R, 0, "Simple LTV", true); setFormula(R, 1, `IF(${abs(1, rChurn)}>0,${abs(1, rGrossProfit)}/${abs(1, rChurn)},${abs(1, rGrossProfit)}*${abs(1, rMonths)})`, USD2, true); R++;
  const rDiscountedLTV = R; setLabel(R, 0, "Discounted LTV", true); setFormula(R, 1, `SUM(${rel(1, rDiscountedGP)}:${rel(months, rDiscountedGP)})`, USD2, true); R++;
  const rLtvToCac = R; setLabel(R, 0, "LTV / CAC", true); setFormula(R, 1, `IF(${abs(1, rCac)}>0,${abs(1, rSimpleLTV)}/${abs(1, rCac)},"n/a")`, MULT, true, true); R++;
  R++;

  setLabel(R, 0, "Months below CAC (helper)");
  const rMonthsBelow = R; setFormula(R, 1, `COUNTIF(${rel(1, rCumulativeGP)}:${rel(months, rCumulativeGP)},"<"&${abs(1, rCac)})`, NUM0); R++;
  setLabel(R, 0, "Cumulative GP just before crossing (helper)");
  const rPrevCum = R; setFormula(R, 1, `IF(${abs(1, rMonthsBelow)}=0,0,INDEX(${rel(1, rCumulativeGP)}:${rel(months, rCumulativeGP)},1,${abs(1, rMonthsBelow)}))`, USD2); R++;
  setLabel(R, 0, "Cumulative GP at crossing month (helper)");
  const rCrossCum = R; setFormula(R, 1, `IF(${abs(1, rMonthsBelow)}>=${abs(1, rMonths)},NA(),INDEX(${rel(1, rCumulativeGP)}:${rel(months, rCumulativeGP)},1,${abs(1, rMonthsBelow)}+1))`, USD2); R++;
  const rPaybackMonth = R; setLabel(R, 0, "CAC payback month", true);
  setFormula(
    R, 1,
    `IFERROR(${abs(1, rMonthsBelow)}+(${abs(1, rCac)}-${abs(1, rPrevCum)})/(${abs(1, rCrossCum)}-${abs(1, rPrevCum)}),"not reached")`,
    "0.00", true, true
  );
  R++;
  R++;

  // ── Sensitivity — LTV/CAC across monthly churn (rows) and CAC (columns) ──
  setLabel(R, 0, "Sensitivity — LTV / CAC", true); R++;
  setLabel(R, 0, "Churn ↓ / CAC →");
  const cacHeaderRow = R;
  for (let ci = 0; ci < sensitivity.cacSteps.length; ci++) {
    h.setCell(R, ci + 1, { v: sensitivity.cacSteps[ci], t: "n", z: USD2, s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, fill: { fgColor: { rgb: CLR.teal } }, alignment: { horizontal: "right", vertical: "center" } } });
  }
  R++;
  sensitivity.grid.forEach((row, ri) => {
    const churnRowIdx = R;
    h.setCell(R, 0, { v: sensitivity.churnSteps[ri], t: "n", z: PCT, s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, alignment: { horizontal: "left", vertical: "center" } } });
    row.forEach((cell, ci) => {
      const f = `(${abs(1, rGrossProfit)}/${rel(0, churnRowIdx)})/${rel(ci + 1, cacHeaderRow)}`;
      setFormula(R, ci + 1, f, MULT);
    });
    R++;
  });
  R++;

  setLabel(R, 0, "Assumptions were generated by AI and should be verified; every calculation above is a live Excel formula.");
  R++;

  const ws_ = h.finalize();
  const wb = XLSXStyle.utils.book_new();
  XLSXStyle.utils.book_append_sheet(wb, ws_, "Unit Economics");

  return {
    wb,
    refs: {
      rows: {
        arpu: rArpu, grossMargin: rMargin, churn: rChurn, cac: rCac, discountRate: rDiscount, months: rMonths,
        grossProfitPerMonth: rGrossProfit,
        survival: rSurvival, expectedGP: rExpectedGP, cumulativeGP: rCumulativeGP, discountedGP: rDiscountedGP,
        avgLifetime: rAvgLifetime, simpleLTV: rSimpleLTV, discountedLTV: rDiscountedLTV, ltvToCac: rLtvToCac,
        paybackMonth: rPaybackMonth,
      },
    },
  };
}

// Builds the cap table workbook. Returns { wb, refs }.
//
// The round-by-round price-per-share / option-pool / SAFE-conversion math,
// and the exit waterfall's convert-vs-take-preference decision, are both
// genuinely circular (each depends on a value that depends back on it) —
// Excel only resolves that with manual iterative calculation turned on,
// which isn't something a written file can force on for the person opening
// it, and formula-evaluation libraries (including the one used in this
// project's own tests) reject it outright as #CYCLE!. Those numbers are
// written as computed values from lib/capTable.js's iterative solver, not
// live formulas — the same "computed snapshot" treatment already used for
// the DCF/LBO sensitivity grids. Ownership percentages and the exit-value
// check row ARE live formulas, since those are plain (non-circular) division
// and summation once the share counts are known.
export function buildCapTableWorkbook(assumptions, capTableResult, payoutTable) {
  const a = assumptions;
  const h = makeSheetHelpers();
  const { abs, setLabel, setFormula } = h;

  let R = titleBlock(h, `Cap Table — ${a.companyName}`);

  // Clear note about the one remaining calculated (non-formula) section.
  for (let c = 0; c <= 5; c++) {
    h.setCell(R, c, {
      v: c === 0
        ? "Note: the exit payout table (bottom of this sheet) is a calculated value from an iterative solver, not a live formula — each investor's convert-or-take-preference decision depends on the very payout it's deciding between, so changing an assumption here will NOT automatically recalculate it. Light gray cells are these calculated payout values; everything above, including round pricing and ownership %, is a live formula."
        : "",
      t: "s",
      s: {
        fill: { fgColor: { rgb: CLR.snapshotGray } },
        font: { italic: true, sz: 9, color: { rgb: CLR.dark } },
        alignment: { horizontal: "left", vertical: "center", wrapText: true },
      },
    });
  }
  h.ws["!merges"].push({ s: { r: R, c: 0 }, e: { r: R, c: 5 } });
  R += 2;

  // ── Assumptions: founders, option pool ──
  setLabel(R, 0, "Founders", true); R++;
  const founderRows = a.founders.map((f) => {
    const r = R; setLabel(r, 0, f.name); h.setInput(r, 1, f.shares, NUM0); R++;
    return r;
  });
  const rOptionPool = R; setLabel(R, 0, "Existing option pool shares"); h.setInput(R, 1, a.optionPoolShares, NUM0); R++;
  R++;

  // ── Assumptions: rounds ──
  setLabel(R, 0, "Rounds", true); R++;
  const roundInputRows = a.rounds.map((round) => {
    setLabel(R, 0, round.name, true); R++;
    const rPre = R; setLabel(R, 0, "  Pre-money ($)"); h.setInput(R, 1, round.preMoney, USD); R++;
    const rInv = R; setLabel(R, 0, "  Investment ($)"); h.setInput(R, 1, round.investment, USD); R++;
    const rPool = R; setLabel(R, 0, "  Target option pool %"); h.setInput(R, 1, round.targetOptionPoolPct, PCT); R++;
    const rLiq = R; setLabel(R, 0, "  Liquidation preference"); h.setInput(R, 1, round.liquidationPreference, MULT); R++;
    return { name: round.name, rPre, rInv, rPool, rLiq };
  });
  R++;

  // ── Assumptions: SAFEs ──
  let safeInputRows = [];
  if (a.safes.length) {
    setLabel(R, 0, "SAFEs (convert in the first priced round)", true); R++;
    safeInputRows = a.safes.map((safe) => {
      setLabel(R, 0, safe.name, true); R++;
      const rAmt = R; setLabel(R, 0, "  Amount ($)"); h.setInput(R, 1, safe.amount, USD); R++;
      const rCap = R; setLabel(R, 0, "  Valuation cap ($)"); h.setInput(R, 1, safe.cap, USD); R++;
      const rDisc = R; setLabel(R, 0, "  Discount"); h.setInput(R, 1, safe.discount, PCT); R++;
      return { name: safe.name, rAmt, rCap, rDisc };
    });
    R++;
  }

  // ── Round-by-round results — closed-form live formulas, no iteration ──
  // Every new share count is a fraction of the post-round fully-diluted
  // total T: investor shares = T*investment/postMoney, the pool after the
  // round = T*targetPct (so top-up = that minus the existing pool), and
  // each SAFE converts at whichever of its cap price or discount price is
  // lower. Substituting those into "T = prior + top-up + SAFE shares +
  // investor shares" turns the pool and SAFE terms into T-weighted sums
  // (Kcap/Kdisc), which rearranges into one direct formula for T — see
  // solveRoundClosedForm in lib/capTable.js for the full derivation.
  //
  // Whether the pool top-up is active, and whether each SAFE is cap- or
  // discount-governed, are resolved *live* too — not decided at export
  // time. writeCapTableRegimeHelpers (below) computes every combination of
  // those yes/no choices side by side in a hidden table and flags which one
  // is self-consistent; SUMPRODUCT then picks that column out live, so
  // changing a SAFE's cap, its discount, or the existing pool size in Excel
  // can flip which regime governs and the sheet still gets it right.
  setLabel(R, 0, "Round results (live formulas)", true); R++;
  let priorRoundRefs = null;
  const roundResultRows = capTableResult.rounds.map((round, ri) => {
    const input = roundInputRows[ri];
    const safeInputsThisRound = ri === 0 ? safeInputRows : [];
    const safeResultsThisRound = ri === 0 ? round.safeConversions : [];

    setLabel(R, 0, round.name, true); R++;

    const rPriorFD = R;
    setLabel(R, 0, "  Fully diluted shares (prior)");
    if (priorRoundRefs) setFormula(R, 1, `${abs(1, priorRoundRefs.rFDAfter)}`, NUM0);
    else setFormula(R, 1, `${founderRows.map((fr) => h.rel(1, fr)).join("+")}+${abs(1, rOptionPool)}`, NUM0);
    R++;

    const rPriorPool = R;
    setLabel(R, 0, "  Existing option pool shares (prior)");
    setFormula(R, 1, priorRoundRefs ? `${abs(1, priorRoundRefs.rPoolCumulative)}` : `${abs(1, rOptionPool)}`, NUM0);
    R++;

    const rPostMoney = R;
    setLabel(R, 0, "  Post-money ($)");
    setFormula(R, 1, `${abs(1, input.rPre)}+${abs(1, input.rInv)}`, USD);
    R++;

    // Hidden helper table: every combination of (pool active?, each SAFE
    // cap- or discount-governed?) computed side by side, so the "which one
    // is actually self-consistent" pick below is a live SUMPRODUCT, not a
    // choice baked in at export time.
    const helperCtx = {
      priorFDAddr: abs(1, rPriorFD),
      priorPoolAddr: abs(1, rPriorPool),
      postMoneyAddr: abs(1, rPostMoney),
      targetPctAddr: abs(1, input.rPool),
      investmentAddr: abs(1, input.rInv),
      safes: safeInputsThisRound.map((si, i) => ({
        name: safeResultsThisRound[i].name,
        amtAddr: abs(1, si.rAmt),
        capAddr: abs(1, si.rCap),
        discAddr: abs(1, si.rDisc),
      })),
    };
    const helpers = writeCapTableRegimeHelpers(h, R, helperCtx);
    h.ws["!rows"] = h.ws["!rows"] || [];
    for (let hr = helpers.startRow; hr < helpers.endRow; hr++) h.ws["!rows"][hr] = { hidden: true };
    R = helpers.endRow;

    const rFDAfter = R;
    setLabel(R, 0, "  Fully diluted shares after (T)", true);
    setFormula(R, 1, `SUMPRODUCT(${helpers.consistentRange},${helpers.TRange})`, NUM0, true);
    R++;

    const rPrice = R;
    setLabel(R, 0, "  Price per share");
    setFormula(R, 1, `${abs(1, rPostMoney)}/${abs(1, rFDAfter)}`, USD2);
    R++;

    const rPoolTopUp = R;
    setLabel(R, 0, "  Option pool top-up shares");
    setFormula(R, 1, `SUMPRODUCT(${helpers.consistentRange},${helpers.poolTopUpRange})`, NUM0);
    R++;

    const rPoolCumulative = R;
    setLabel(R, 0, "  Option pool shares (cumulative)");
    setFormula(R, 1, `${abs(1, rPriorPool)}+${abs(1, rPoolTopUp)}`, NUM0);
    R++;

    const safeShareRows = safeResultsThisRound.map((sc) => {
      const r = R;
      setLabel(R, 0, `  ${sc.name} conversion shares`);
      setFormula(R, 1, `SUMPRODUCT(${helpers.consistentRange},${helpers.safeSharesRangeByName[sc.name]})`, NUM0);
      R++;
      return { name: sc.name, row: r };
    });

    const rNewInvShares = R;
    setLabel(R, 0, "  New investor shares");
    setFormula(R, 1, `${abs(1, rFDAfter)}*${abs(1, input.rInv)}/${abs(1, rPostMoney)}`, NUM0);
    R++;

    priorRoundRefs = { rFDAfter, rPoolCumulative };
    return { name: round.name, rPrice, rPoolTopUp, rPoolCumulative, safeShareRows, rNewInvShares, rFDAfter };
  });
  R++;

  // ── Final cap table — every share count and ownership % is a live formula ──
  const liveShareRefByName = {};
  a.founders.forEach((f, i) => { liveShareRefByName[f.name] = founderRows[i]; });
  if (roundResultRows.length) {
    liveShareRefByName["Option Pool"] = roundResultRows[roundResultRows.length - 1].rPoolCumulative;
  } else {
    liveShareRefByName["Option Pool"] = rOptionPool;
  }
  roundResultRows.forEach((rr) => {
    rr.safeShareRows.forEach((sr) => { liveShareRefByName[sr.name] = sr.row; });
    liveShareRefByName[`${rr.name} investor`] = rr.rNewInvShares;
  });

  setLabel(R, 0, "Final cap table", true); R++;
  setHeaderPair(h, R, "Holder", "Shares", "Ownership %");
  R++;
  const holderShareRows = capTableResult.holders.map((holder) => {
    const r = R; setLabel(R, 0, `${holder.name}${holder.type === "founder" ? "" : ` (${holder.type})`}`);
    const sourceRow = liveShareRefByName[holder.name];
    if (sourceRow !== undefined) setFormula(R, 1, `${abs(1, sourceRow)}`, NUM0);
    else h.setPlainNum(R, 1, holder.shares, NUM0);
    R++;
    return { name: holder.name, row: r };
  });
  const rTotalShares = R;
  setLabel(R, 0, "Total", true);
  setFormula(R, 1, `SUM(${h.rel(1, holderShareRows[0].row)}:${h.rel(1, holderShareRows[holderShareRows.length - 1].row)})`, NUM0, true, true);
  R++;
  // Ownership % column — a live formula for every holder, referencing the total above.
  holderShareRows.forEach(({ row }) => {
    setFormula(row, 2, `${h.rel(1, row)}/${abs(1, rTotalShares)}`, PCT);
  });
  setFormula(rTotalShares, 2, `${abs(1, rTotalShares)}/${abs(1, rTotalShares)}`, PCT, true, true);
  R++;

  // ── Exit payout table (computed snapshot) with a live sum-check per column ──
  setLabel(R, 0, "Exit payout table (computed snapshot)", true); R++;
  setLabel(R, 0, "Holder");
  const multipleHeaderRow = R;
  payoutTable.columns.forEach((col, ci) => {
    h.setCell(R, ci + 1, { v: `${col.multiple}x`, t: "s", s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, fill: { fgColor: { rgb: CLR.teal } }, alignment: { horizontal: "right", vertical: "center" } } });
  });
  R++;
  setLabel(R, 0, "Exit value ($)");
  payoutTable.columns.forEach((col, ci) => h.setSnapshotNum(R, ci + 1, col.exitValue, USD));
  R++;
  const payoutRows = capTableResult.holders.map((holder) => {
    const r = R;
    setLabel(R, 0, holder.name);
    payoutTable.columns.forEach((col, ci) => {
      const p = col.payouts.find((x) => x.name === holder.name);
      h.setSnapshotNum(R, ci + 1, p ? p.payout : 0, USD);
    });
    R++;
    return r;
  });
  const rPayoutCheck = R;
  setLabel(R, 0, "Check: total payout (should equal exit value)", true);
  payoutTable.columns.forEach((col, ci) => {
    setFormula(R, ci + 1, `SUM(${h.rel(ci + 1, payoutRows[0])}:${h.rel(ci + 1, payoutRows[payoutRows.length - 1])})`, USD, true, true);
  });
  R++;
  R++;

  setLabel(R, 0, "Assumptions were generated by AI and should be verified. Round pricing and ownership % are live formulas; the exit payout table is a computed value from an iterative solver (see note above).");
  R++;

  const ws_ = h.finalize();
  const wb = XLSXStyle.utils.book_new();
  XLSXStyle.utils.book_append_sheet(wb, ws_, "Cap Table");

  return {
    wb,
    refs: {
      founderRows,
      rOptionPool,
      roundInputRows,
      safeInputRows,
      roundResultRows,
      holderShareRows,
      totalSharesRow: rTotalShares,
      payoutRows,
      payoutCheckRow: rPayoutCheck,
      multipleHeaderRow,
    },
  };
}

// Writes a hidden helper table resolving, for one round, which pricing
// regime actually governs — live in Excel, with no circular references.
//
// Whether the option pool top-up is "active" (positive) and whether each
// SAFE converts at its cap or its discount are each yes/no questions that
// can depend on the very total T they help determine. Rather than pick one
// answer at export time, this computes T under *every* combination of
// those yes/no choices (pool active/inactive x each SAFE cap/discount) —
// each one is a direct, non-circular formula — then flags which
// combination is self-consistent (its own assumption matches what the
// resulting numbers actually imply) and lets Excel's own SUMPRODUCT pick
// that one out live. One column per combination, one row per metric, so
// "pick the consistent column" is a same-row SUMPRODUCT over a contiguous
// range. See solveRoundClosedForm in lib/capTable.js for where this
// combinatorial approach comes from — this mirrors it in formulas.
function writeCapTableRegimeHelpers(h, startRow, ctx) {
  const { setLabel, setFormula } = h;
  const { priorFDAddr, priorPoolAddr, postMoneyAddr, targetPctAddr, investmentAddr, safes } = ctx;
  const n = safes.length;
  const combos = [];
  for (const poolActive of [true, false]) {
    for (let mask = 0; mask < (1 << n); mask++) combos.push({ poolActive, mask });
  }

  let R = startRow;
  const rKcap = R; setLabel(R, 0, "Helper — Σ amount/cap (cap-governed)"); R++;
  const rKdisc = R; setLabel(R, 0, "Helper — Σ amount/(1-discount) (discount-governed)"); R++;
  const rT = R; setLabel(R, 0, "Helper — candidate T"); R++;
  const rPoolTopUp = R; setLabel(R, 0, "Helper — candidate pool top-up"); R++;
  const rPoolOK = R; setLabel(R, 0, "Helper — pool assumption self-consistent?"); R++;
  const safeRows = safes.map((s) => {
    const rCapPrice = R; setLabel(R, 0, `Helper — ${s.name} cap price`); R++;
    const rDiscPrice = R; setLabel(R, 0, `Helper — ${s.name} discount price`); R++;
    const rSafeOK = R; setLabel(R, 0, `Helper — ${s.name} assumption self-consistent?`); R++;
    const rSafeShares = R; setLabel(R, 0, `Helper — ${s.name} candidate shares`); R++;
    return { name: s.name, rCapPrice, rDiscPrice, rSafeOK, rSafeShares };
  });
  const rConsistent = R; setLabel(R, 0, "Helper — this combination self-consistent?"); R++;

  combos.forEach(({ poolActive, mask }, ci) => {
    const col = ci + 1;

    const capTerms = [];
    const discTerms = [];
    safes.forEach((s, i) => {
      if ((mask >> i) & 1) capTerms.push(`${s.amtAddr}/${s.capAddr}`);
      else discTerms.push(`${s.amtAddr}/(1-${s.discAddr})`);
    });
    setFormula(rKcap, col, capTerms.length ? capTerms.join("+") : "0", NUM0);
    setFormula(rKdisc, col, discTerms.length ? discTerms.join("+") : "0", NUM0);
    const KcapRef = h.rel(col, rKcap);
    const KdiscRef = h.rel(col, rKdisc);

    const tFormula = poolActive
      ? `((${priorFDAddr}-${priorPoolAddr})*(1+${KcapRef}))/(1-${targetPctAddr}*(1+${KcapRef})-(${KdiscRef}+${investmentAddr})/${postMoneyAddr})`
      : `(${priorFDAddr}*(1+${KcapRef}))/(1-(${KdiscRef}+${investmentAddr})/${postMoneyAddr})`;
    setFormula(rT, col, tFormula, NUM0);
    const TRef = h.rel(col, rT);

    setFormula(rPoolTopUp, col, poolActive ? `MAX(${TRef}*${targetPctAddr}-${priorPoolAddr},0)` : "0", NUM0);
    const poolTopUpRef = h.rel(col, rPoolTopUp);

    setFormula(
      rPoolOK, col,
      poolActive ? `${TRef}*${targetPctAddr}-${priorPoolAddr}>=-0.000001` : `${TRef}*${targetPctAddr}-${priorPoolAddr}<=0.000001`,
      "@"
    );
    const poolOKRef = h.rel(col, rPoolOK);

    const safeOKRefs = [];
    safes.forEach((s, i) => {
      const sr = safeRows[i];
      setFormula(sr.rCapPrice, col, `${s.capAddr}/(${priorFDAddr}+${poolTopUpRef})`, USD2);
      setFormula(sr.rDiscPrice, col, `(${postMoneyAddr}/${TRef})*(1-${s.discAddr})`, USD2);
      const capRef = h.rel(col, sr.rCapPrice);
      const discRef = h.rel(col, sr.rDiscPrice);
      const assumedCapGoverns = !!((mask >> i) & 1);
      setFormula(sr.rSafeOK, col, assumedCapGoverns ? `${capRef}<=${discRef}` : `${discRef}<=${capRef}`, "@");
      setFormula(sr.rSafeShares, col, `${s.amtAddr}/MIN(${capRef},${discRef})`, NUM0);
      safeOKRefs.push(h.rel(col, sr.rSafeOK));
    });

    setFormula(rConsistent, col, `AND(${[poolOKRef, ...safeOKRefs].join(",")})`, "@");
  });

  const endRow = R;
  const numCombos = combos.length;
  const rowRange = (row) => `${h.rel(1, row)}:${h.rel(numCombos, row)}`;

  return {
    startRow,
    endRow,
    consistentRange: rowRange(rConsistent),
    TRange: rowRange(rT),
    poolTopUpRange: rowRange(rPoolTopUp),
    safeSharesRangeByName: Object.fromEntries(safeRows.map((sr) => [sr.name, rowRange(sr.rSafeShares)])),
  };
}

function setHeaderPair(h, r, ...labels) {
  labels.forEach((text, i) => h.setCell(r, i, { v: text, t: "s", s: { font: { bold: true, sz: 10, color: { rgb: CLR.black } }, fill: { fgColor: { rgb: CLR.teal } }, alignment: { horizontal: i === 0 ? "left" : "right", vertical: "center" } } }));
}
